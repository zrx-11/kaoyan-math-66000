"""草稿字数试算：口径同 gate_one.plain，不改任何 HTML 文件。"""
import re

def plain(html):
    t = re.sub(r"<[^>]+>", "", html)
    t = re.sub(r"\\[a-zA-Z]+", "", t)
    t = re.sub(r"[\\${}^_]", "", t)
    return re.sub(r"\s+", "", t)

